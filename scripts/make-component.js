#!/usr/bin/env node
// Mechanical component scaffolder - does the one real mechanical step left
// under the auto-discovery model (src/components/registry.js's
// `import.meta.glob('/components/*/index.js', { eager: true })` finds
// whatever is on disk - there is nothing to hand-edit): the existing-component
// collision check, and the components/<name>/index.js skeleton from
// .claude/skills/artefact-builder/reference/component-template.js.
//
// It does NOT generate kind-specific behaviour (a real D3 chart, an SVG
// diagram, etc.) - that's a creative/domain step. After running this, read
// the matching recipe in .claude/skills/artefact-builder/reference/ and
// flesh out render()/static styles in the new index.js.
//
// Usage:
//   node scripts/make-component.js --name <kebab> --kind chart|circle-pack|diagram|hero|interactive|basic
// Add --dry-run to print the plan without touching disk.

import { existsSync, mkdirSync, readFileSync, writeFileSync } from 'node:fs';
import { dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const COMPONENTS_DIR = resolve(root, 'components'); // repo root - deck content, per src/components/README.md
const TEMPLATE_PATH = resolve(root, '.claude/skills/artefact-builder/reference/component-template.js');

const RECIPES = {
	chart: 'reference/d3-chart.md',
	'circle-pack': 'reference/d3-circle-pack.md',
	diagram: 'reference/svg-diagram.md',
	hero: 'reference/gsap-hero.md',
	interactive: 'reference/alpine-interactive.md',
	'radial-meter': 'reference/radial-meter.md',
	'stat-tiles': 'reference/stat-tiles.md',
	'animated-counter': 'reference/animated-counter.md',
	'confidence-bars': 'reference/confidence-bars.md',
	'timeline-stepper': 'reference/timeline-stepper.md',
	basic: 'reference/component-template.js (already the base - no extra recipe)',
};

function parseArgs(argv) {
	const args = {};
	for (let i = 0; i < argv.length; i++) {
		const a = argv[i];
		if (a === '--dry-run') { args.dryRun = true; continue; }
		if (!a.startsWith('--')) continue;
		args[a.slice(2)] = argv[++i];
	}
	return args;
}

function fail(message) {
	console.error(`✗ ${message}`);
	process.exit(1);
}

function toPascalCase(kebab) {
	return kebab.split('-').filter(Boolean).map((w) => w[0].toUpperCase() + w.slice(1)).join('');
}

const args = parseArgs(process.argv.slice(2));
if (!args.name) fail('--name <kebab> is required');
if (!/^[a-z][a-z0-9]*(-[a-z0-9]+)*$/.test(args.name)) fail('--name must be kebab-case (e.g. "hero-title")');
if (!args.kind || !RECIPES[args.kind]) fail(`--kind must be one of: ${Object.keys(RECIPES).join(', ')}`);

const name = args.name;
const tag = `deck-${name}`;
const pascal = toPascalCase(name);
const componentDir = resolve(COMPONENTS_DIR, name);
const indexPath = resolve(componentDir, 'index.js');

// components/<name>/ existing on disk IS the collision check - registry.js
// auto-discovers whatever's here at build time, there is no separate list.
if (existsSync(indexPath)) {
	fail(`components/${name}/index.js already exists (tag <${tag}>) - edit it directly, don't overwrite.`);
}

if (!existsSync(TEMPLATE_PATH)) fail(`${TEMPLATE_PATH} not found`);
const template = readFileSync(TEMPLATE_PATH, 'utf8');
// drop the template's own "replace <Name>/<name>" authoring-instructions
// comment (already done, by this script) and swap in a normal file header
const templateBody = template.replace(/^\/\*\*[\s\S]*?\*\/\n/, '');
const header = `// components/${name}/index.js - generated by scripts/make-component.js.\n// Kind: ${args.kind}. Flesh out render() / static styles per the recipe printed below.\n`;
const indexContent = header + templateBody.split('<Name>').join(pascal).split('<name>').join(name);

console.log(args.dryRun ? '(dry run - no files touched)' : 'Applying:');
console.log(`  write components/${name}/index.js`);
console.log(`  (registry.js auto-discovers it - nothing else to edit)`);

if (args.dryRun) process.exit(0);

mkdirSync(componentDir, { recursive: true });
writeFileSync(indexPath, indexContent, 'utf8');

console.log(`\n✓ created components/${name}/index.js (tag <${tag}>)`);
console.log(`\nNext: read .claude/skills/artefact-builder/${RECIPES[args.kind]} and flesh out`);
console.log(`render() / static styles in components/${name}/index.js. SHARED_STYLES is already`);
console.log(`prepended - pull any other shared visual pieces from it too, never re-declare them.`);
