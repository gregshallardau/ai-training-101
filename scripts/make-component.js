#!/usr/bin/env node
// Mechanical component scaffolder - does the exact, error-prone-by-hand parts
// of artefact-builder's "Write" step: the existing-component collision check,
// the src/components/<name>/index.js skeleton (from
// .claude/skills/artefact-builder/reference/component-template.js), and the
// two-line registry.js edit (import + COMPONENTS entry, per
// reference/registry-edit.md).
//
// It does NOT generate kind-specific behaviour (a real D3 chart, an SVG
// diagram, etc.) - that's a creative/domain step. After running this, read
// the matching recipe in .claude/skills/artefact-builder/reference/ and
// flesh out render()/static styles in the new index.js.
//
// Usage:
//   node scripts/make-component.js --name <kebab> --kind chart|circle-pack|diagram|hero|interactive|basic
// Add --dry-run to print the plan without touching disk.

import { existsSync, mkdirSync, readFileSync, writeFileSync } from 'node:fs';
import { dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const REGISTRY_PATH = resolve(root, 'src/components/registry.js');
const TEMPLATE_PATH = resolve(root, '.claude/skills/artefact-builder/reference/component-template.js');

const RECIPES = {
	chart: 'reference/d3-chart.md',
	'circle-pack': 'reference/d3-circle-pack.md',
	diagram: 'reference/svg-diagram.md',
	hero: 'reference/gsap-hero.md',
	interactive: 'reference/alpine-interactive.md',
	basic: 'reference/component-template.js (already the base - no extra recipe)',
};

function parseArgs(argv) {
	const args = {};
	for (let i = 0; i < argv.length; i++) {
		const a = argv[i];
		if (a === '--dry-run') { args.dryRun = true; continue; }
		if (!a.startsWith('--')) continue;
		args[a.slice(2)] = argv[++i];
	}
	return args;
}

function fail(message) {
	console.error(`✗ ${message}`);
	process.exit(1);
}

function toPascalCase(kebab) {
	return kebab.split('-').filter(Boolean).map((w) => w[0].toUpperCase() + w.slice(1)).join('');
}

const args = parseArgs(process.argv.slice(2));
if (!args.name) fail('--name <kebab> is required');
if (!/^[a-z][a-z0-9]*(-[a-z0-9]+)*$/.test(args.name)) fail('--name must be kebab-case (e.g. "hero-title")');
if (!args.kind || !RECIPES[args.kind]) fail(`--kind must be one of: ${Object.keys(RECIPES).join(', ')}`);

const name = args.name;
const tag = `deck-${name}`;
const pascal = toPascalCase(name);
const componentDir = resolve(root, `src/components/${name}`);
const indexPath = resolve(componentDir, 'index.js');

if (!existsSync(REGISTRY_PATH)) fail(`${REGISTRY_PATH} not found`);
const registryText = readFileSync(REGISTRY_PATH, 'utf8');
const registryWithoutComments = registryText.replace(/\/\*[\s\S]*?\*\//g, '').replace(/\/\/.*$/gm, '');
if (registryWithoutComments.includes(`'${name}':`) || registryWithoutComments.includes(`tag: '${tag}'`)) {
	fail(`"${name}" (or tag "${tag}") already exists in src/components/registry.js - edit it directly, don't overwrite.`);
}
if (existsSync(indexPath)) fail(`${indexPath} already exists`);

if (!existsSync(TEMPLATE_PATH)) fail(`${TEMPLATE_PATH} not found`);
const template = readFileSync(TEMPLATE_PATH, 'utf8');
// drop the template's own "replace <Name>/<name>" authoring-instructions
// comment (already done, by this script) and swap in a normal file header
const templateBody = template.replace(/^\/\*\*[\s\S]*?\*\/\n/, '');
const header = `// src/components/${name}/index.js - generated by scripts/make-component.js.\n// Kind: ${args.kind}. Flesh out render() / static styles per the recipe printed below.\n`;
const indexContent = header + templateBody.split('<Name>').join(pascal).split('<name>').join(name);

// --- registry.js edit: insert the import line + COMPONENTS entry, alphabetically among the real (uncommented) entries ---
function insertImport(text) {
	const lines = text.split('\n');
	const importLineRe = /^import '\.\/([\w-]+)\/index\.js';$/;
	let lastRealImportIdx = -1;
	let headerIdx = -1;
	lines.forEach((line, i) => {
		if (importLineRe.test(line)) {
			const existingName = line.match(importLineRe)[1];
			if (existingName < name) lastRealImportIdx = i;
		}
		if (headerIdx === -1 && /component imports/.test(line)) headerIdx = i;
	});
	const insertAt = lastRealImportIdx !== -1 ? lastRealImportIdx + 1 : headerIdx + 1;
	lines.splice(insertAt, 0, `import './${name}/index.js';`);
	return lines.join('\n');
}

function insertComponentsEntry(text) {
	const lines = text.split('\n');
	const entryLineRe = /^\t'([\w-]+)':\s*\{ tag: '[\w-]+',\s*dir: '[\w-]+' \},$/;
	let lastRealEntryIdx = -1;
	let openIdx = -1;
	lines.forEach((line, i) => {
		if (entryLineRe.test(line)) {
			const existingName = line.match(entryLineRe)[1];
			if (existingName < name) lastRealEntryIdx = i;
		}
		if (openIdx === -1 && /export const COMPONENTS = \{/.test(line)) openIdx = i;
	});
	const insertAt = lastRealEntryIdx !== -1 ? lastRealEntryIdx + 1 : openIdx + 1;
	lines.splice(insertAt, 0, `\t'${name}': { tag: '${tag}', dir: '${name}' },`);
	return lines.join('\n');
}

const newRegistryText = insertComponentsEntry(insertImport(registryText));

console.log(args.dryRun ? '(dry run - no files touched)' : 'Applying:');
console.log(`  write src/components/${name}/index.js`);
console.log(`  edit src/components/registry.js (+import, +COMPONENTS entry)`);

if (args.dryRun) process.exit(0);

mkdirSync(componentDir, { recursive: true });
writeFileSync(indexPath, indexContent, 'utf8');
writeFileSync(REGISTRY_PATH, newRegistryText, 'utf8');

console.log(`\n✓ created src/components/${name}/index.js (tag <${tag}>)`);
console.log(`✓ registered in src/components/registry.js`);
console.log(`\nNext: read .claude/skills/artefact-builder/${RECIPES[args.kind]} and flesh out`);
console.log(`render() / static styles in src/components/${name}/index.js. Pull shared visual`);
console.log(`pieces (button/chip/token-row/box/etc.) from reference/component-styles.md verbatim.`);
